"""Render tools/gh2e/sheets/<Class>.json as docs/gh2e/<Class>.md (readable card sheets) and docs/gh2e/index.md.

  python tools/gh2e/sheet_md.py
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
DOCS = os.path.join(REPO, "docs", "gh2e")


def cmp_text(v):
    if v in (None, "", []):
        return "-"
    if isinstance(v, str):
        return v
    return "<br>".join(str(x) for x in v)


def half(h):
    if not h:
        return "-"
    lines = "<br>".join(str(x).replace("|", "/") for x in h.get("lines") or [])
    s = h.get("summary") or []
    return lines + (f"<br>*[{', '.join(s)}]*" if s else "")


def render(sheet):
    out = [f"# {sheet['class']} (Gloomhaven 2nd edition)", "",
           f"Read from the card images ({sheet.get('read_by', '')}). Image wins; GHS = Gloomhaven Secretariat, "
           "Xipe = Xipe's Gloomhaven digital mod. Generated by `tools/gh2e/sheet_md.py` from "
           f"`tools/gh2e/sheets/{sheet['class']}.json`.", ""]
    cards = sheet.get("cards") or []
    agree_g = sum(1 for c in cards if c.get("ghs") == "agrees")
    agree_x = sum(1 for c in cards if c.get("xipe") == "agrees")
    has_g = sum(1 for c in cards if c.get("ghs") not in ("missing", None))
    has_x = sum(1 for c in cards if c.get("xipe") not in ("missing", None))
    customs = sum(len(c.get("custom") or []) for c in cards)
    out += [f"**{len(cards)} cards.** GHS agrees on {agree_g} of {has_g}; Xipe agrees on {agree_x} of {has_x}. "
            f"Special rules to translate: {customs}.", ""]
    for k, title in (("summons", "Summons"), ("mechanics", "Class mechanics"), ("unclear", "Unclear")):
        v = sheet.get(k) or []
        if v:
            out += [f"**{title}:**", ""] + [f"- {x if isinstance(x, str) else json.dumps(x, ensure_ascii=False)}" for x in v] + [""]
    out += ["| # | Card | Lvl | Init | Top | Bottom | GHS | Xipe | Special rules |", "|---|---|---|---|---|---|---|---|---|"]
    for c in cards:
        out.append("| {n} | **{name}** | {lvl} | {ini} | {top} | {bot} | {g} | {x} | {cu} |".format(
            n=c.get("number", ""), name=c.get("name", ""), lvl=c.get("level", ""), ini=c.get("initiative", ""),
            top=half(c.get("top")), bot=half(c.get("bottom")), g=cmp_text(c.get("ghs")).replace("|", "/"),
            x=cmp_text(c.get("xipe")).replace("|", "/"),
            cu=cmp_text(c.get("custom")).replace("|", "/") + (f"<br>*{c['notes']}*" if c.get("notes") else "")))
    return "\n".join(out) + "\n", len(cards), customs, agree_g, has_g


def main():
    os.makedirs(DOCS, exist_ok=True)
    rows = []
    for f in sorted(glob.glob(os.path.join(HERE, "sheets", "*.json"))):
        if f.endswith(".B.json"):
            continue  # a second reading, folded into the main sheet by compare_reads + a check
        with open(f, encoding="utf-8") as fh:
            sheet = json.load(fh)
        text, n, customs, ag, hg = render(sheet)
        with open(os.path.join(DOCS, sheet["class"] + ".md"), "w", encoding="utf-8") as fh:
            fh.write(text)
        rows.append(f"| [{sheet['class']}]({sheet['class']}.md) | {n} | {customs} | {ag}/{hg} | "
                    f"{len(sheet.get('summons') or [])} | {len(sheet.get('mechanics') or [])} | {len(sheet.get('unclear') or [])} |")
        print(sheet["class"], n, "cards")
    with open(os.path.join(DOCS, "index.md"), "w", encoding="utf-8") as fh:
        fh.write("# Gloomhaven 2nd edition: card sheets\n\nSee [README](README.md) for the format and credits.\n\n"
                 "| Class | Cards | Special rules | GHS agrees | Summons | Mechanics | Unclear |\n|---|---|---|---|---|---|---|\n"
                 + "\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
